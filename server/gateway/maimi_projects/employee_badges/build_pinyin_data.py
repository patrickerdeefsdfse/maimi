"""Build a deterministic compact runtime table from the pinned public Unihan archive."""
import base64
import hashlib
import re
import struct
import sys
import unicodedata
import zipfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE_URL = 'https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip'
SOURCE_SHA256 = 'f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e'


def unaccented(reading):
    # Mandarin has four tone marks. Umlaut and circumflex distinguish syllables.
    letters = ''.join(c for c in unicodedata.normalize('NFD', reading)
                      if c not in '\u0304\u0301\u030c\u0300')
    return unicodedata.normalize('NFC', letters)


def main(source):
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('Unihan 17.0 archive digest mismatch')
    readings = {}
    with zipfile.ZipFile(source) as archive, archive.open('Unihan_Readings.txt') as entries:
        for data in entries:
            if b'\tkMandarin\t' not in data:
                continue
            point, _, variants = data.decode().strip().split('\t')
            reading = unaccented(variants.split()[0])
            if not re.fullmatch('[a-züê]+', reading):
                raise ValueError(f'Unexpected reading for {point}')
            readings[int(point[2:], 16)] = reading
    syllables = ['', *sorted(set(readings.values()))]
    indices = {word: index for index, word in enumerate(syllables)}
    first = min(readings)
    slots = bytearray(2 * (max(readings) - first + 1))
    for point, reading in readings.items():
        struct.pack_into('>H', slots, 2 * (point - first), indices[reading])
    data = base64.b85encode(zlib.compress(slots, 9))
    notice = (ROOT / 'UNICODE-LICENSE.txt').read_text(encoding='utf-8-sig').strip()
    lines = ['"""Generated by build_pinyin_data.py from the Unihan 17.0 kMandarin field.',
             SOURCE_URL, 'Upstream SHA256: ' + SOURCE_SHA256, '',
             *notice.splitlines(), '"""', f'FIRST = {first}', 'SYLLABLES = (']
    for start in range(0, len(syllables), 10):
        lines.append('    ' + ', '.join(map(repr, syllables[start:start + 10])) + ',')
    lines.extend([')', 'PACKED_READINGS = ('])
    lines.extend('    ' + repr(data[i:i+96]) for i in range(0, len(data), 96))
    lines += [')', '']
    target = ROOT / 'name_pinyin_data.py'
    target.write_bytes('\n'.join(lines).encode())
    print('Unihan characters:', len(readings), 'Syllables:', len(syllables) - 1,
          'Module bytes:', target.stat().st_size)


if __name__ == '__main__':
    main(Path(sys.argv[1]))
