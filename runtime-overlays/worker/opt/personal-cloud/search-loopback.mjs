import { deny } from './search-permits.mjs';

const SAFE_CODES = new Set(['SEARCH_AUTH_REQUIRED', 'SEARCH_SCOPE_REVOKED', 'SEARCH_SELECTION_CHANGED', 'SEARCH_NOT_SELECTED',
  'SEARCH_MODEL_UNAVAILABLE_FOR_ACCOUNT', 'SEARCH_UPSTREAM_UNSUPPORTED', 'SEARCH_UPSTREAM_UNAVAILABLE', 'SEARCH_RESPONSE_INVALID',
  'SEARCH_TIMEOUT', 'SEARCH_BUSY', 'SEARCH_REQUEST_INVALID', 'SEARCH_REPLAY', 'SEARCH_NO_RESULT', 'SEARCH_BING_FAILED']);
const FALLBACK = new Set(['SEARCH_MODEL_UNAVAILABLE_FOR_ACCOUNT', 'SEARCH_UPSTREAM_UNSUPPORTED', 'SEARCH_UPSTREAM_UNAVAILABLE',
  'SEARCH_RESPONSE_INVALID', 'SEARCH_TIMEOUT', 'SEARCH_BUSY', 'SEARCH_NO_RESULT']);
const message = code => ({ error: { message: code }, code });
const sameKeys = (value, keys) => value && !Array.isArray(value) && Object.keys(value).sort().join(',') === keys;
function queryFrom(value) {
  const prefix = 'Perform a web search for the query: ';
  if (!sameKeys(value, 'max_tokens,messages,model,tools') || value.model !== 'deepseek-v4.1-flash'
      || value.max_tokens !== 2048 || !Array.isArray(value.messages) || value.messages.length !== 1
      || !sameKeys(value.messages[0], 'content,role') || value.messages[0].role !== 'user'
      || !Array.isArray(value.messages[0].content) || value.messages[0].content.length !== 1
      || !sameKeys(value.messages[0].content[0], 'text,type') || value.messages[0].content[0].type !== 'text'
      || typeof value.messages[0].content[0].text !== 'string' || !value.messages[0].content[0].text.startsWith(prefix)
      || !Array.isArray(value.tools) || value.tools.length !== 1 || !sameKeys(value.tools[0], 'max_uses,name,type')
      || value.tools[0].type !== 'web_search_20250305' || value.tools[0].name !== 'web_search' || value.tools[0].max_uses !== 1)
    deny('SEARCH_REQUEST_INVALID', 400);
  const query = value.messages[0].content[0].text.slice(prefix.length);
  if (!query.trim() || query.length > 400) deny('SEARCH_REQUEST_INVALID', 400);
  return query;
}

async function body(req) {
  let size = 0; const chunks = [];
  for await (const chunk of req) { size += chunk.length; if (size > 8192) deny('SEARCH_REQUEST_INVALID', 400); chunks.push(chunk); }
  try { return JSON.parse(Buffer.concat(chunks).toString('utf8')); } catch { deny('SEARCH_REQUEST_INVALID', 400); }
}

export function createSearchLoopback({ permits, remote, enter = () => () => {} }) {
  async function handle(req, res) {
    let permit, finish = () => {}, abort;
    const reply = (status, value) => { if (!res.headersSent && !res.destroyed) { res.writeHead(status,
      { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }); res.end(JSON.stringify(value)); } };
    try {
      if (req.method !== 'POST' || !['/__megmeet/search/messages', '/__megmeet/search/decision', '/__megmeet/search/fallback'].includes(req.url))
        deny('SEARCH_REQUEST_INVALID', 404);
      const token = req.headers.authorization?.startsWith('Bearer ') ? req.headers.authorization.slice(7) : '';
      permit = await permits.get(token);
      const operation = req.url.split('/').pop();
      const value = await body(req); await permits.verify(permit);
      if (operation === 'decision') {
        if (!sameKeys(value, '')) deny('SEARCH_REQUEST_INVALID', 400);
        reply(200, { fallback_allowed: permit.allowFallback && !permit.fallbackUsed,
          code: permit.lastCode || 'SEARCH_NO_RESULT' }); return;
      }
      if (operation === 'messages') {
        if (permit.messagesUsed || permit.fallbackUsed) deny('SEARCH_REPLAY', 409);
        permit.query = queryFrom(value);
        permit.messagesUsed = true;
      } else {
        if (!permit.messagesUsed || !permit.allowFallback || permit.fallbackUsed) deny('SEARCH_REPLAY', 409);
        if (!sameKeys(value, 'count,query') || typeof value.query !== 'string' || value.query !== permit.query
            || !Number.isInteger(value.count) || value.count < 1 || value.count > 10) deny('SEARCH_REQUEST_INVALID', 400);
        permit.fallbackUsed = true;
      }
      abort = new AbortController(); req.once('aborted', () => abort.abort());
      res.once('close', () => { if (!res.writableFinished) abort.abort(); });
      const signal = AbortSignal.any([permit.controller.signal, abort.signal, AbortSignal.timeout(70000)]);
      finish = enter({ work: true, task: permit.task });
      const result = await remote(operation, { native_session_id: permit.scope.rootSessionId,
        invocation_id: permit.id, body: value }, { lease: permit.lease, signal });
      signal.throwIfAborted(); await permits.verify(permit);
      if (operation === 'messages') {
        // query is generated by the real official provider. Gateway has already
        // strictly validated its shape; save only for exact fallback binding.
        permit.allowFallback = true; permit.lastCode = 'SEARCH_NO_RESULT';
      }
      reply(200, result);
    } catch (error) {
      const code = SAFE_CODES.has(error?.code) ? error.code : 'SEARCH_SCOPE_REVOKED';
      if (permit && req.url === '/__megmeet/search/messages') {
        permit.allowFallback = FALLBACK.has(code); permit.lastCode = code;
      }
      reply(Number.isInteger(error?.status) ? error.status : 403, message(code));
    } finally { finish(); }
  }
  return { handle };
}
